class IntegrationTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.path=Path(self.tmp.name)/'test.gcode';self.path.write_bytes(job())
        self.h=PurgeHarness((.2,.2,219.8,219.8))
        sd=self.h.objects['virtual_sdcard'];sd.sdcard_dirname=self.tmp.name
        sd.data.update(file_path=str(self.path),is_active=True,progress=.001)

    def tearDown(self):self.tmp.cleanup()

    def test_fallback_reached_via_native_macro_and_dispatch_and_dry_run_is_inert(self):
        self.h.objects['toolhead'].data['homed_axes']=''
        self.h.objects['extruder'].data['can_extrude']=False
        self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.assertTrue(any('actual_paths=' in m for m in self.h.messages))
        self.assertFalse(any('Unknown command' in m for m in self.h.messages))
        self.assertEqual(self.h.motion,[]);self.assertEqual(self.h.commands,[])

    def test_full_fallback_motion_preserves_sensors_acceleration_and_e_state(self):
        before=self.h.move.get_status(1.)
        self.h.gcode.run_script('LINE_PURGE')
        self.assertGreater(len(self.h.motion),5)
        self.assertTrue(self.h.sensor_enabled);self.assertEqual(self.h.accel,20000)
        self.assertEqual(self.h.move.get_status(1.)['absolute_extrude'],before['absolute_extrude'])
        self.assertGreaterEqual(self.h.motion[-1][0][2],5)
        self.assertEqual(self.h.retracts,1)

    def test_explicit_filename_only_nonmoving_and_confined_to_sd_root(self):
        self.h.objects['virtual_sdcard'].data.update(file_path=None,is_active=False)
        self.h.gcode.run_script('PLAN_EDGE_PURGE DRY_RUN=1 FILE="test.gcode"')
        for cmd in ['PLAN_EDGE_PURGE FILE="test.gcode"',
                    'PLAN_EDGE_PURGE DRY_RUN=1 FILE="../elsewhere.gcode"']:
            with self.assertRaises(gcode.CommandError):self.h.gcode.run_script(cmd)
        self.assertEqual(self.h.motion,[])

    def test_malformed_file_and_inactive_print_do_not_move_or_change_sensors(self):
        self.path.write_bytes(b'invalid')
        with self.assertRaises(gcode.CommandError):self.h.gcode.run_script('LINE_PURGE')
        self.path.write_bytes(job())
        self.h.objects['virtual_sdcard'].data['is_active']=False
        with self.assertRaises(gcode.CommandError):self.h.gcode.run_script('LINE_PURGE')
        self.assertEqual(self.h.motion,[]);self.assertTrue(self.h.sensor_enabled)

    def test_nonzero_stationary_blob_refused_by_fallback(self):
        self.h.objects['gcode_macro _KAMP_Settings'].data['tip_distance']=5.
        with self.assertRaisesRegex(gcode.CommandError,'stationary blobs'):
            self.h.gcode.run_script('LINE_PURGE')
        self.assertEqual(self.h.motion,[])

    def test_cache_rechecks_file_content_even_if_size_and_mtime_are_preserved(self):
        self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.assertIn('cached=1',self.h.messages[-1])
        stamp=self.path.stat()
        data=self.path.read_bytes().replace(b'by layer',b'by objct')
        self.path.write_bytes(data)
        os.utime(self.path,ns=(stamp.st_atime_ns,stamp.st_mtime_ns))
        with self.assertRaises(gcode.CommandError):self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.assertEqual(self.h.motion,[])

    def test_cache_replans_after_margin_or_timelapse_changes(self):
        self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.h.objects['gcode_macro _KAMP_Settings'].data['purge_margin']=21.
        self.h.gcode.run_script('LINE_PURGE DRY_RUN=1')
        self.assertIn('cached=0',self.h.messages[-1])


