# Synthetic L, with a large empty corner inside its aggregate bounding box.
POLYGON = [(1,1),(219,1),(219,219),(175,219),(175,45),(1,45)]


def job(body=None, poly=POLYGON, header='G90\nM83'):
    if body is None:
        body = ('G1 X1 Y1\nG1 Z.25\n;WIDTH:0.5\n' +
                ''.join('G1 X%s Y%s E1\n' % v for v in poly[1:]+poly[:1]))
    return ('; generated by OrcaSlicer test\n'
            'EXCLUDE_OBJECT_DEFINE NAME=shape POLYGON='+json.dumps(poly)+'\n'+
            header+'\n;LAYER_CHANGE\n;Z:0.25\n'+body+
            '\n;LAYER_CHANGE\n;Z:1.50\n; print_sequence = by layer\n').encode()


def geometry(data=None, **kwargs):
    return p.parse_paths(io.BytesIO(job() if data is None else data),1.3,**kwargs)


def plan(g):
    return p.choose_edge(g,(0,0,220,220),30,.8,20)


def distance_point_segment(pt,a,b):
    d = (b[0]-a[0],b[1]-a[1])
    n = d[0]*d[0]+d[1]*d[1]
    t = max(0,min(1,((pt[0]-a[0])*d[0]+(pt[1]-a[1])*d[1])/n)) if n else 0
    return math.hypot(pt[0]-a[0]-t*d[0],pt[1]-a[1]-t*d[1])


def sequential_job(transition='G1 Z10\nG1 X160 Y170\n', high=''):
    return ('; generated by OrcaSlicer test\n'
            'EXCLUDE_OBJECT_DEFINE NAME=one POLYGON=[[80,80],[100,80],[100,100],[80,100]]\n'
            'EXCLUDE_OBJECT_DEFINE NAME=two POLYGON=[[160,160],[180,160],[180,180],[160,180]]\n'
            'G90\nM83\n;LAYER_CHANGE\n;Z:0.2\nG1 X80 Y80\nG1 Z.2\n'
            'EXCLUDE_OBJECT_START NAME=one\nG1 X100 Y80 E1\nEXCLUDE_OBJECT_END NAME=one\n'
            ';LAYER_CHANGE\n;Z:10\nG1 Z10\nEXCLUDE_OBJECT_START NAME=one\n' + high +
            'G1 X100 Y100 E1\nEXCLUDE_OBJECT_END NAME=one\n' + transition +
            ';LAYER_CHANGE\n;Z:0.2\nEXCLUDE_OBJECT_START NAME=two\n'
            'G1 X160 Y160 Z.2\nG1 X180 Y160 E1\nEXCLUDE_OBJECT_END NAME=two\n'
            'END_PRINT\n; print_sequence = by object\n').encode()


class SequentialTests(unittest.TestCase):
    def test_second_object_brim_and_descent_are_included(self):
        g=geometry(sequential_job())
        self.assertEqual((g['objects'],g['layers']),(2,2))
        self.assertIn(((160.,170.),(160.,160.),.5),g['segments'])
        self.assertIn(((160.,160.),(180.,160.),.5),g['segments'])
        self.assertEqual(g['bytes'],len(sequential_job()))

    def test_fast_scan_matches_unskipped_parse_across_chunk_boundaries(self):
        high=('G1 X90 E.1\nG1 Y95\n;TYPE:Inner wall\nSET_VELOCITY_LIMIT ACCEL=5000\n' * 1700)
        data=sequential_job(high=high,transition='G1 X42\nG1 Y43\nG1 Z.2\nG1 X160 Y170\n')
        fast=geometry(data)
        with unittest.mock.patch.object(p,'_HIGH_RUN',re.compile(rb'(?!)')):
            slow=geometry(data)
        self.assertEqual(fast,slow)
        self.assertIn(((42.,43.),(160.,170.),.5),fast['segments'])

    def test_later_low_dip_after_high_layer_is_not_skipped(self):
        data=sequential_job(high='G1 X90 Y90\nG1 Z.3\nG1 X3 Y3 E1\nG1 Z10\n')
        self.assertTrue(any(b==(3.,3.) for a,b,w in geometry(data)['segments']))

    def test_relative_motion_disables_fast_skip(self):
        data=sequential_job(high='G91\nG1 X2 Y3 E.1\nG1 Z-9.8\nG1 X5 Y6\nG90\nG1 Z10\n')
        fast=geometry(data)
        with unittest.mock.patch.object(p,'_HIGH_RUN',re.compile(rb'(?!)')):
            self.assertEqual(fast,geometry(data))

    def test_fast_coordinates_ignore_comments_and_preserve_high_width(self):
        data=sequential_job(high='G1 X92Y93Z10 E.1\n; X3 Y4 Z.1 E99\n;WIDTH:4.5\n',
                            transition='G1 Z.2\nG1 X160 Y170 E.2\n')
        fast=geometry(data)
        with unittest.mock.patch.object(p,'_HIGH_RUN',re.compile(rb'(?!)')):
            self.assertEqual(fast,geometry(data))
        self.assertIn(((100.,100.),(160.,170.),2.25),fast['segments'])

    def test_taller_bead_does_not_skip_z_two_moves(self):
        data=sequential_job(high='G1 X90 Y90\nG1 Z2.1\nG1 X3 Y3 E1\nG1 Z10\n')
        g=p.parse_paths(io.BytesIO(data),2.3)
        self.assertTrue(any(b==(3.,3.) for a,b,w in g['segments']))

    def test_missing_objects_truncation_and_interleaving_are_rejected(self):
        data=sequential_job()
        for bad in [data.replace(b'END_PRINT',b''),
                    data.replace(b'NAME=two',b'NAME=one'),
                    data.replace(b'EXCLUDE_OBJECT_END NAME=two',b'EXCLUDE_OBJECT_END NAME=one'),
                    data.replace(b'G90',b'EXCLUDE_OBJECT_DEFINE NAME=missing POLYGON=[[1,1],[2,1],[2,2]]\nG90')]:
            with self.subTest(bad=bad[-150:]),self.assertRaises(p.PlanError):geometry(bad)

    def test_unsupported_high_commands_and_post_end_moves_fail_closed(self):
        for cmd in ['G28','G92 X0','G2 X20 Y20 I1 J1','CUSTOM_MOVE','SET_GCODE_OFFSET Z1']:
            with self.subTest(cmd=cmd),self.assertRaises(p.PlanError):
                geometry(sequential_job(high=cmd+'\n'))
        with self.assertRaises(p.PlanError):
            geometry(sequential_job().replace(b'END_PRINT',b'END_PRINT\nG1 Z10\nG1 X3 Y3'))

    def test_tool_changes_require_reviewed_contract_and_safe_height(self):
        data=sequential_job(transition='T2\nG1 X160 Y170\n')
        with self.assertRaisesRegex(p.PlanError,'reviewed AD5X'):geometry(data)
        self.assertEqual(geometry(data,toolchange=True)['objects'],2)
        for transition in ['G1 Z.2\nT2\n','T4\n','T2 EXTRA=1\n']:
            with self.assertRaises(p.PlanError):geometry(sequential_job(transition=transition),toolchange=True)

    def test_absolute_e_after_skipped_relative_e_requires_reset(self):
        data=sequential_job(high='G1 X90 E.1\nM82\nG1 X91 E2\nM83\n')
        with self.assertRaisesRegex(p.PlanError,'G92 E'):geometry(data)
        self.assertEqual(geometry(data.replace(b'M82\n',b'M82\nG92 E0\n'))['objects'],2)

    def test_later_object_can_block_previously_clear_edge(self):
        data=sequential_job().replace(b'G1 X180 Y160 E1',b'G1 X1 Y1 E1\nG1 X219 Y1 E1\nG1 X219 Y219 E1\nG1 X1 Y219 E1\nG1 X1 Y1 E1')
        with self.assertRaisesRegex(p.PlanError,'no clear edge'):plan(geometry(data))

    def test_sequential_cache_checks_later_object_content(self):
        with tempfile.TemporaryDirectory() as tmp:
            path=Path(tmp)/'seq.gcode'
            # Put the changed object outside both the initial prefix and footer.
            data=sequential_job(high='G1 X95 Y95 E.1\n'*45000)
            data=data.replace(b'END_PRINT',b'END_PRINT\n'+b'; completed job padding\n'*24000)
            path.write_bytes(data)
            h=PurgeHarness();h.objects['virtual_sdcard'].sdcard_dirname=tmp
            h.gcode.run_script('PLAN_EDGE_PURGE DRY_RUN=1 FILE="seq.gcode"')
            h.gcode.run_script('PLAN_EDGE_PURGE DRY_RUN=1 FILE="seq.gcode"')
            self.assertIn('cached=1',h.messages[-1])
            stamp=path.stat();path.write_bytes(data.replace(b'G1 X180 Y160 E1',b'G1 X003 Y003 E1'))
            os.utime(path,ns=(stamp.st_atime_ns,stamp.st_mtime_ns))
            h.gcode.run_script('PLAN_EDGE_PURGE DRY_RUN=1 FILE="seq.gcode"')
            self.assertIn('cached=0',h.messages[-1])
            self.assertEqual(h.motion,[])

